# Joins the altar, pad and summit GLBs into one upload (VoxelKit.glb) and writes where each mesh goes to
# src/shared/VoxelKitData.lua, so the game places every mesh itself, whatever Import 3D did to the origin.
import sys, os, json
OUT = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, OUT)
import bpy, vox
from mathutils import Vector
for o in list(bpy.data.objects): bpy.data.objects.remove(o)
PIECES = ()  # only the altar and pad are voxel; every other structure stays brick
for f in ("altar_pilot", "pad_pilot") + PIECES:
    bpy.ops.import_scene.gltf(filepath=f"{OUT}/{f}.glb")
obs = [o for o in bpy.data.objects if o.type == "MESH"]
data = {"Altar": {}, "Pad": {}, **{k: {} for k in PIECES}}
for o in obs:
    w = [o.matrix_world @ v.co for v in o.data.vertices]
    lo = Vector((min(p[i] for p in w) for i in range(3))); hi = Vector((max(p[i] for p in w) for i in range(3)))
    c, s = (lo + hi) / 2, hi - lo
    flat = [p for p in o.data.polygons if abs(p.normal.z) > 0.5]
    top = max(flat, key=lambda p: (o.matrix_world @ p.center).z)
    n = (o.matrix_world.to_3x3() @ top.normal).z
    assert n > 0.5, ("inside-out", o.name, n)
    tris = sum(len(p.vertices) - 2 for p in o.data.polygons)
    assert tris < 20000, (o.name, tris)
    assert len(o.data.color_attributes) > 0, o.name
    piece = next(k for k in data if o.name.startswith(k))
    data[piece][o.name] = ((c.x, c.z, -c.y), (s.x, s.z, s.y))   # Blender (x, y, z) is Roblox (x, -z, y)
    print(o.name, tris, "normal ok")
vox.export(OUT + "/VoxelKit.glb", obs)
L = ["-- GENERATED by art/voxel_pilot/kit.py: where each VoxelKit mesh goes (centre and size, studs) in its piece's space.", "return {"]
for piece, parts in data.items():
    L.append(f"\t{piece} = {{")
    for n, (c, s) in sorted(parts.items()):
        L.append("\t\t%s = { c = Vector3.new(%.3f, %.3f, %.3f), s = Vector3.new(%.3f, %.3f, %.3f) }," % (n, *c, *s))
    L.append("\t},")
L.append("}\n")
open(OUT + "/../../src/shared/VoxelKitData.lua", "w").write("\n".join(L))
print("KITDONE", len(obs))
