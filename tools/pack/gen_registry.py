"""Writes src/shared/Fighters.lua from tools/pack/roster.json and tools/pack/launch.json.

    python3 tools/pack/gen_registry.py

The registry is the only place the game learns which fighters exist. `model` is the name of the
model in ReplicatedStorage.Assets.Fighters (written by strip_pack.py), so replacing a fighter's look
is changing that one field. `display` is what players read.

launch.json picks the launch roster (docs/ROSTER_LAUNCH.md): each launch fighter's `pool` (Hub, a zone name,
or Divine for the summon-only top tier), its launch `rarity` (income follows it) and whether it is a boss
`exclusive` (never dropped, summoned or gifted). Fighters not in it stay in the registry (old saves keep
working) but never appear in play.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# Cash per second by rarity (big numbers: kids like watching the K, M, B and T climb).
INCOME = {"Common": 100, "Uncommon": 400, "Rare": 2000, "Epic": 10000, "Legendary": 80000, "Mythic": 600000,
          "Secret": 5000000}
# Within a rarity: stronger forms earn 25% more, alternate outfits 20% less, so which one you pull matters.
STRONG = re.compile(r"Awakened|Mode|Bankai|Gates|Godspeed|Blue|Sage|Kcm|Final|Hollow|Shunko|Ssj|Lssj|PostTimeSkip"
                    r"|^Ts|8Th|5Th|100|Jagan|Vasto|Mugetsu|Max$|Beerus", re.I)
OUTFIT = re.compile(r"Alt$|Formal|Suit|JuniorHigh|^Pts|^R1$|^R2$")


def income(key, rarity):
    k = 1.25 if STRONG.search(key) else 0.8 if OUTFIT.search(key) else 1
    value = INCOME[rarity] * k
    step = 10 ** (len(str(int(value))) - 2)  # two significant figures
    return int(round(value / step) * step)


# Signature poses (clips Sig* in shared/Clips.lua, authored in tools/blender/r15_studio.py), written into the
# registry so regenerating never loses them.
SIGNATURES = """-- Signature poses (clips Sig* in shared/Clips.lua, authored in tools/blender/r15_studio.py): each series'
-- iconic stance, played when a fighter lands, wins, goes on a stand or is revealed. A few characters have
-- their own.
local SIGNATURE_BY_SERIES = {
	JJK = "SigGojo",
	JOJO = "SigJojo",
	DBZ = "SigKamehameha",
	NARUTO = "SigSeal",
	["One Piece"] = "SigLaugh",
	["My Hero Academia"] = "SigSmash",
	AOT = "SigSalute",
	Bleach = "SigBankai",
	HXH = "SigJajanken",
	FATE = "SigSword",
	YYH = "SigSpiritGun",
	["Fairy Tail"] = "SigGuild",
}
local SIGNATURE_BY_KEY = {
	Sukuna = "SigSukuna",
	AllMight = "SigAllMight",
	AllMightMode = "SigAllMight",
	Cell = "SigFlex",
	Mahoraga = "SigFlex",
	GoldenFrieza = "SigFlex",
}

function Fighters.signature(key)
	local fighter = Fighters.ByKey[key]
	return SIGNATURE_BY_KEY[key] or (fighter and SIGNATURE_BY_SERIES[fighter.series]) or "SigFlex"
end
""".split("\n")


def main():
    with open(os.path.join(ROOT, "tools", "pack", "roster.json")) as f:
        roster = json.load(f)
    with open(os.path.join(ROOT, "tools", "pack", "launch.json")) as f:
        launch = json.load(f)
    # Player-facing names (tools/pack/names.json): recognisable, never the exact anime name.
    with open(os.path.join(ROOT, "tools", "pack", "names.json")) as f:
        names = json.load(f)
    lines = [
        "-- Generated by tools/pack/gen_registry.py from tools/pack/roster.json. Do not edit by hand:",
        "-- change the roster (or the rarity lists in inspect_pack.py) and regenerate.",
        "local Fighters = {}",
        "Fighters.List = {",
    ]
    for f in roster:
        l = launch.get(f["key"])
        rarity = l["rarity"] if l else f["rarity"]
        extra = ""
        if l:
            extra = ", pool = %s, launch = true" % lua_string(l["pool"])
            if l["exclusive"]:
                extra += ", exclusive = true"
        lines.append(
            "\t{ key = %s, display = %s, series = %s, rarity = %s, income = %d, model = %s%s },"
            % (lua_string(f["key"]), lua_string(names["display"].get(f["key"], f["display"])),
               lua_string(f["series"]), lua_string(rarity),
               income(f["key"], rarity), lua_string(f["key"]), extra)
        )
    lines += [
        "}",
        "-- What players read for each series (the series keys stay internal).",
        "Fighters.SeriesNames = {",
    ] + ["\t[%s] = %s," % (lua_string(k), lua_string(v)) for k, v in sorted(names["series"].items())] + [
        "}",
        "-- ByKey: every fighter (old saves). Launch: the launch roster, in list order. ByRarity: what summons,",
        "-- the Secret Rush and gifts draw from (launch, no boss exclusives). ByPool[pool][rarity]: what each",
        "-- zone's altars drop (Hub, Blossom, Ninja, Pirate, Walled; the Divine pool is never dropped).",
        "Fighters.ByKey = {}",
        "Fighters.Launch = {}",
        "Fighters.ByRarity = {}",
        "Fighters.ByPool = {}",
        "for _, fighter in Fighters.List do",
        "\tFighters.ByKey[fighter.key] = fighter",
        "\tif fighter.launch then",
        "\t\ttable.insert(Fighters.Launch, fighter)",
        "\t\tif not fighter.exclusive then",
        "\t\t\tFighters.ByRarity[fighter.rarity] = Fighters.ByRarity[fighter.rarity] or {}",
        "\t\t\ttable.insert(Fighters.ByRarity[fighter.rarity], fighter)",
        "\t\t\tlocal pool = Fighters.ByPool[fighter.pool] or {}",
        "\t\t\tFighters.ByPool[fighter.pool] = pool",
        "\t\t\tpool[fighter.rarity] = pool[fighter.rarity] or {}",
        "\t\t\ttable.insert(pool[fighter.rarity], fighter)",
        "\t\tend",
        "\tend",
        "end",
    ] + SIGNATURES + [
        "return Fighters",
        "",
    ]
    out = os.path.join(ROOT, "src", "shared", "Fighters.lua")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"{len(roster)} fighters -> {os.path.relpath(out, ROOT)}")


if __name__ == "__main__":
    main()
